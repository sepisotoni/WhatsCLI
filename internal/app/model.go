package app

import (
	"context"
	"strings"

	tea "github.com/charmbracelet/bubbletea"
	"whatscli/internal/history"
	"whatscli/internal/ui"
)

type screen int

const (
	welcomeScreen screen = iota
	consentScreen
	pairingScreen
	inboxScreen
	settingsScreen
	helpScreen
	commandScreen
)

type conversationsLoadedMsg struct {
	conversations []history.Conversation
	err           error
}

type Model struct {
	repo            history.Repository
	active          screen
	width           int
	conversations   []history.Conversation
	loadErr         error
	filter          string
	commandIndex    int
	consentAccepted bool
	quitting        bool
}

var commands = []string{"conversations", "help", "quit", "settings"}

func New(repo history.Repository) Model {
	return Model{repo: repo, active: welcomeScreen}
}

func (m Model) Init() tea.Cmd {
	if m.repo == nil {
		return nil
	}
	return func() tea.Msg {
		conversations, err := m.repo.ListConversations(context.Background())
		return conversationsLoadedMsg{conversations: conversations, err: err}
	}
}

func (m Model) Update(msg tea.Msg) (tea.Model, tea.Cmd) {
	switch msg := msg.(type) {
	case tea.WindowSizeMsg:
		m.width = msg.Width
	case conversationsLoadedMsg:
		m.conversations = msg.conversations
		m.loadErr = msg.err
	case tea.KeyMsg:
		m = m.updateKey(msg)
		if m.quitting {
			return m, tea.Quit
		}
	}
	return m, nil
}

func (m Model) updateKey(key tea.KeyMsg) Model {
	if key.String() == "ctrl+c" {
		m.quitting = true
		return m
	}
	if m.active == commandScreen {
		return m.updateCommand(key)
	}

	switch key.String() {
	case "q":
		m.quitting = true
	case "/":
		m.active = commandScreen
		m.filter = ""
		m.commandIndex = 0
	case "s":
		if m.active == inboxScreen {
			m.active = settingsScreen
		}
	case " ":
		if m.active == consentScreen {
			m.consentAccepted = !m.consentAccepted
		}
	case "esc":
		switch m.active {
		case consentScreen:
			m.active = welcomeScreen
		case pairingScreen:
			m.active = consentScreen
		case settingsScreen, helpScreen:
			m.active = inboxScreen
		}
	case "enter":
		switch m.active {
		case welcomeScreen:
			m.active = consentScreen
		case consentScreen:
			if m.consentAccepted {
				m.active = pairingScreen
			}
		}
	case "i":
		if m.active == pairingScreen {
			m.active = inboxScreen
		}
	}
	return m
}

func (m Model) updateCommand(key tea.KeyMsg) Model {
	matches := m.filteredCommands()
	switch key.String() {
	case "esc":
		m.active = inboxScreen
		m.filter = ""
	case "up":
		if m.commandIndex > 0 {
			m.commandIndex--
		}
	case "down":
		if m.commandIndex < len(matches)-1 {
			m.commandIndex++
		}
	case "backspace":
		if len(m.filter) > 0 {
			m.filter = m.filter[:len(m.filter)-1]
			m.commandIndex = 0
		}
	case "enter":
		if len(matches) > 0 {
			m.runCommand(matches[m.commandIndex])
		}
	default:
		if key.Type == tea.KeyRunes {
			m.filter += string(key.Runes)
			m.commandIndex = 0
		}
	}
	return m
}

func (m *Model) runCommand(command string) {
	m.filter = ""
	m.commandIndex = 0
	switch command {
	case "conversations":
		m.active = inboxScreen
	case "help":
		m.active = helpScreen
	case "quit":
		m.quitting = true
	case "settings":
		m.active = settingsScreen
	}
}

func (m Model) filteredCommands() []string {
	var filtered []string
	for _, command := range commands {
		if strings.Contains(command, strings.ToLower(m.filter)) {
			filtered = append(filtered, command)
		}
	}
	return filtered
}

func (m Model) View() string {
	width := m.width
	if width <= 0 {
		width = 72
	}
	switch m.active {
	case welcomeScreen:
		return ui.Panel("Welcome to WhatsCLI", "Your conversations. Your terminal.\n\nEnter · get started     q · exit", width)
	case consentScreen:
		return ui.Panel("Disclaimer & consent", m.consentView(), width)
	case pairingScreen:
		return ui.Panel("Link a device", "WhatsApp transport is not connected in this foundation build, so no QR code or pairing request is available.\n\n1  Open WhatsApp on your phone.\n2  Go to Settings or Menu → Linked devices.\n3  Choose Link a device when a code is available.\n4  Keep the terminal open during linking.\n\nNever share a pairing code. No code is generated by this build.\n\ni · open local inbox     Esc · back", width)
	case settingsScreen:
		return ui.Panel("Settings", "This foundation build stores local history in a private SQLite database.\nMouse input is optional and currently disabled.\n\nEsc · back     / · commands", width)
	case helpScreen:
		return ui.Panel("Help", "Enter · continue from welcome\nSpace · accept the disclaimer\ni · open local inbox from link screen\n/ · filter and run commands\ns · open settings\nEsc · back     q · quit", width)
	case commandScreen:
		return ui.Panel("Commands", m.commandView(), width)
	default:
		return ui.Panel("Conversations", m.inboxView(), width)
	}
}

func (m Model) consentView() string {
	accepted := "[ ]"
	if m.consentAccepted {
		accepted = "[x]"
	}
	lines := []string{
		"STEP 01 / 02",
		"",
		"01  Independent and unofficial",
		"WhatsCLI is independent and not endorsed by WhatsApp or Meta.",
		"",
		"02  Your account, your responsibility",
		"Connecting an unofficial client may carry account risks.",
		"",
		"03  Local data storage",
		"Local history is not encrypted; this build stores no device credentials.",
		"",
		"04  Early software",
		"Features may be incomplete; do not rely on this for critical communication.",
		"",
		accepted + " I understand this is unofficial and accept these risks.",
		"",
		"Space · toggle     Enter · agree and continue     Esc · back",
	}
	return strings.Join(lines, "\n")
}

func (m Model) inboxView() string {
	if m.loadErr != nil {
		return "Could not load local history: " + m.loadErr.Error() + "\n\n/ · commands     s · settings     q · quit"
	}
	if len(m.conversations) == 0 {
		return "No conversations in local history yet.\nMessages will appear here when a messaging transport is connected.\n\n/ · commands     s · settings     q · quit"
	}
	var lines []string
	for _, conversation := range m.conversations {
		lines = append(lines, "• "+conversation.Title)
	}
	return strings.Join(lines, "\n") + "\n\n/ · commands     s · settings     q · quit"
}

func (m Model) commandView() string {
	matches := m.filteredCommands()
	lines := []string{"Filter: /" + m.filter}
	for i, command := range matches {
		prefix := "  "
		if i == m.commandIndex {
			prefix = "> "
		}
		lines = append(lines, prefix+command)
	}
	if len(matches) == 0 {
		lines = append(lines, "  No matching commands")
	}
	lines = append(lines, "", "↑/↓ · select     Enter · run     Esc · close")
	return strings.Join(lines, "\n")
}
